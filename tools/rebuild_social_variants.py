def normalized(text):
    text = text.replace('`', ' ').replace('\\', '').replace('—', ' ').replace('/', ' / ').replace('‘', '').replace('’', '').replace('©', '').replace('®', '')
    text = re.sub(r'(?<=\w)-\s+(?=\w)', '-', text)
    return re.sub(r'\s+', ' ', text).strip(' ,;:.\'"')


