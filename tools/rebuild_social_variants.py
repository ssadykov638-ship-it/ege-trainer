def polish(value):
    for old,new in TYPO_FIXES.items():
        value=value.replace(old,new)
    value=re.sub(r'(?<=\w)[‹°]','',value)
    value=re.sub(r'\s+[‚;]\s+', ' ',value)
    value=re.sub(r'\s*[‚‹]\s*$', '',value)
    value=re.sub(r'(государств[аоеу]|стран[аеыу]|Государство|Банк) [27]\b',r'\1 Z',value)
    return value.strip(' ,;:.')


def pages_text(root, source):
    parts = []
    for path in sorted((root / 'social2026_ocr_variants_v2').glob(f'variant-{source:02d}-page-*.txt')):
        text = path.read_text(encoding='utf-8')
        text = re.split(r'(?m)Копирование|^.*©\s*2026', text, maxsplit=1)[0]
        text = re.sub(r'(?m)^.*(?:ВАРИАНТ|ЕГЭ\. ТИПОВЫЕ).*$','',text)
        parts.append(text)
    return '\n'.join(parts)


def blocks(text, starts):
    positions = []
    cursor = 0
    for start in starts:
        pattern = r'\s+'.join(re.escape(word) for word in start.split())
        found = re.search(pattern, text[cursor:])
        if not found:
            raise ValueError(f'Missing boundary: {start}')
        position = cursor + found.start()
        positions.append(position)
        cursor = position + len(found.group())
    return [text[start:positions[i+1] if i+1 < len(positions) else len(text)] for i,start in enumerate(positions)]


def choices(block, answer, chart_stem=None):
    block = re.split(r'(?im)^\s*(?:Ответ\b|Отве[мт]\b|Не забудьте|Часть 2)',block,maxsplit=1)[0]
    matches = list(re.finditer(r'(?<!\d)(\d{1,2})\)\s*',block))
    options = {}
    for index, match in enumerate(matches):
        number = int(match.group(1))
        if number in (8,83):
            number = 3
        if not 1 <= number <= 6:
            continue
        end = matches[index+1].start() if index+1 < len(matches) else len(block)
        value = re.split(r'\b(?:Найдите|Запишите)\b',block[match.end():end],maxsplit=1)[0]
        value = re.split(r'(?<=[.!?])\s*\n', value, maxsplit=1)[0]
        value = normalized(value)
        if number not in options:
            options[number] = value
    if not options or sorted(options) != list(range(1,max(options)+1)):
        raise ValueError(f'Incomplete options: {sorted(options)} {block[:80]}')
    stem = chart_stem or normalized(block[:matches[0].start()])
    return dict(type='multi',text=stem,options=[options[n] for n in sorted(options)],correct=[int(n)-1 for n in answer],explanation=f'Эталон из таблицы ответов: {answer}.')


def main():
    Path('review').mkdir(exist_ok=True)
    parser = argparse.ArgumentParser()
    parser.add_argument('--source-root',type=Path,required=True)
    args = parser.parse_args()
    target = Path('local-interactive.js')
    text = target.read_text(encoding='utf-8')
    source = json.loads(text[text.index('push(')+5:text.rindex(');')])
    tree = ast.parse((args.source_root / 'build_social2026_interactive.py').read_text(encoding='utf-8'))
    keys = {node.targets[0].id:ast.literal_eval(node.value) for node in tree.body if isinstance(node,ast.Assign) and isinstance(node.targets[0],ast.Name) and node.targets[0].id in ('ANSWERS_1_8','ANSWERS_9_16')}
    report = []
    for original, anchors in STARTS.items():
        if original in (23,24,26,29,30):
            anchors[11] = 'Выберите в приведённом списке положения'
        variant = next(v for v in source['variants'] if v['title'] == f'Вариант {original-1}')
        chart = variant['questions'][8]
        try:
            chunks = blocks(pages_text(args.source_root,original),anchors)
        except ValueError as error:
            raise ValueError(f'Source {original}: {error}') from error
        answers = keys['ANSWERS_1_8'][original]+keys['ANSWERS_9_16'][original]
        questions = []
        for number,(block,answer) in enumerate(zip(chunks,answers),1):
            if number in MATCHES[original]:
                left,right = MATCHES[original][number]
                stem = re.split(r'к каждой|к каждому',block,flags=re.I)[0]
                stem = re.split(r'ПРИЗНАКИ|ФУНКЦИИ|ДЕЙСТВИЯ|ПРИМЕРЫ|ПОЛНОМОЧИЯ|ХАРАКТЕРНЫЕ ЧЕРТЫ',stem)[0]
                question = dict(type='match',text=normalized(stem),left=left,right=right,correct=[int(n)-1 for n in answer],explanation=f'Эталон из таблицы ответов: {answer}.')
            else:
                if number == 9:
                    # Statements may continue on the next page; the graph's OCR is excluded.
                    instruction = re.search(r'Найдите в приведённом списке выводы',block)
                    if instruction:
                        block = block[instruction.start():]
                    options_start = re.search(r'(?<!\d)1\)\s+',block)
                    if not options_start:
                        raise ValueError(f'Missing chart statements: {original}')
                    block = block[options_start.start():]
                question = choices(block,answer,CHART_STEMS[original] if number == 9 else None)
                if number == 9:
                    question.update(image=chart['image'],isChart=True,alt='Диаграмма и полная легенда к заданию 9')
            question.update(sourceVariant=original,sourceTask=number)
            question['text']=polish(question['text'])
            if 'options' in question:
                question['options']=[polish(OPTION_FIXES.get((original,number,index+1),value)) for index,value in enumerate(question['options'])]
                if any(index>=len(question['options']) for index in question['correct']):
                    raise ValueError(f'Invalid answer bounds: {original}.{number}')
            questions.append(question)
            report.append(f"{original-1}.{number} {question['type']} {question['text']}\n"+json.dumps(question.get('options',question.get('left')),ensure_ascii=False))
        variant['questions'] = questions
    target.write_text('window.localInteractiveSources = window.localInteractiveSources || [];\nwindow.localInteractiveSources.push('+json.dumps(source,ensure_ascii=False,indent=2)+');\n',encoding='utf-8')
    Path('review/rebuilt-tasks.txt').write_text('\n\n'.join(report),encoding='utf-8')


if __name__ == '__main__':
    main()
